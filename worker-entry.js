/* Cloudflare Workers entry: serves the static site (index.html etc.) and replaces the Netlify _redirects proxy rules. */
export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const p = url.pathname;

    /* Google sign-in: Firebase login pages are served through our own domain */
    if (p.startsWith('/__/auth/') || p === '/__/firebase/init.json') {
      const target = new URL('https://arain-tube-672a1.firebaseapp.com' + p + url.search);
      return fetch(new Request(target, request));
    }
    /* studio.gupzy.com: same site files, the home page is the Studio app */
    if (url.hostname.startsWith('studio.') && (p === '/' || p === '/index.html')) {
      return env.ASSETS.fetch(new Request(url.origin + '/studio/' + url.search, request));
    }
    /* old Studio address -> new subdomain */
    if ((url.hostname === 'gupzy.com' || url.hostname === 'www.gupzy.com') && (p === '/studio' || p === '/studio/')) {
      return Response.redirect('https://studio.gupzy.com/' + url.search + url.hash, 301);
    }
    /* video sitemap is generated by the other Cloudflare worker */
    if (p === '/sitemap-videos.xml') {
      return fetch('https://arain-api.muhammadqasimishtiaq0604.workers.dev/sitemap-videos.xml');
    }
    /* Android app link file lives in /well-known/ in this repo */
    if (p === '/.well-known/assetlinks.json') {
      const r = await env.ASSETS.fetch(new Request(url.origin + '/well-known/assetlinks.json'));
      return new Response(r.body, { status: r.status, headers: { 'content-type': 'application/json', 'cache-control': 'no-cache' } });
    }
    return env.ASSETS.fetch(request);
  }
};
